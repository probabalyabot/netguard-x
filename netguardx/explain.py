"""Deterministic explanation text for findings.

Explanations are templated from verified simulation facts, never generated by a model, so they
cannot claim something the engine did not observe.  A language model can be layered on top to
rephrase them, but the facts come from here.
"""
from __future__ import annotations

from typing import Any

FAILURE_TYPES = {"ROUTING_LOOP", "BLACKHOLE", "INVALID_NEXT_HOP", "FLOW_BLOCKED"}
ROUTING_TYPES = {"ROUTING_LOOP", "BLACKHOLE", "INVALID_NEXT_HOP"}
SECURITY_TYPES = {"POLICY_VIOLATION", "WAYPOINT_BYPASS"}

SEVERITY_RANK = {"critical": 0, "high": 1, "medium": 2, "info": 3}


def svc(proto: str, port) -> str:
    return proto if port is None else f"{proto}/{port}"


def fmt_path(path: list[str]) -> str:
    return " > ".join(path) if path else "(none)"


def _join(items: list[str]) -> str:
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def compose(ftype: str, c: dict[str, Any]) -> tuple[str, str, str, str]:
    """Return (title, technical, human, impact_label) for a finding.

    ``c`` carries: src, dst, proto, port, before_path, after_path, before_detail, after_detail,
    stop_node, root (change description or None), decision (divergence label/detail or None),
    policies (list of ids), waypoint, sources, services, removed, added, rule.
    """
    s, d = c["src"], c["dst"]
    sv = svc(c["proto"], c["port"])
    bp, ap = fmt_path(c["before_path"]), fmt_path(c["after_path"])
    root = c.get("root")
    decision = c.get("decision")
    pids = _join(c.get("policies") or [])
    lead = f"{root}. " if root else ""
    dec = f"{decision} " if decision else ""
    stop = c.get("stop_node")

    if ftype == "POLICY_VIOLATION":
        title = f"{s} can now reach {d} on {sv}, which policy {pids} forbids"
        technical = (
            f"{lead}{dec}Before: {c['before_detail']}. After: the {s}->{d} {sv} flow is delivered along {ap}. "
            f"Policy {pids} requires this traffic to be denied."
        )
        human = (
            f"Traffic from {s} to {d} used to be stopped. After this change it gets through, "
            f"so {d} is reachable in a way your policy does not allow."
        )
        return title, technical, human, f"Forbidden traffic reaches {d}"

    if ftype == "WAYPOINT_BYPASS":
        wp = c.get("waypoint") or "the required device"
        title = f"{s} to {d} ({sv}) no longer passes through {wp}"
        technical = (
            f"{lead}{dec}The {s}->{d} {sv} path changes from {bp} to {ap}. "
            f"Policy {pids} requires traffic to cross {wp}; the new path does not."
        )
        human = (
            f"Traffic from {s} to {d} used to go through {wp}. After this change it takes a path "
            f"that skips {wp}, so whatever {wp} enforces no longer applies to it."
        )
        return title, technical, human, f"{wp} is bypassed"

    if ftype == "ROUTING_LOOP":
        title = f"Forwarding loop for {s} to {d} ({sv})"
        technical = f"{lead}{dec}Before: {bp}. After: {ap}, which revisits {stop}."
        human = f"Packets from {s} to {d} would circle between devices and never arrive."
        return title, technical, human, "Traffic loops and is never delivered"

    if ftype == "BLACKHOLE":
        title = f"{stop} has no route for {s} to {d} ({sv})"
        technical = f"{lead}{dec}Before: {bp}. After: {c['after_detail']}."
        human = f"Traffic from {s} to {d} would be silently discarded at {stop}."
        return title, technical, human, "Traffic is discarded"

    if ftype == "INVALID_NEXT_HOP":
        title = f"{stop} cannot forward {s} to {d} traffic ({sv})"
        technical = f"{lead}{dec}Before: {bp}. After: {c['after_detail']}."
        human = f"{stop} still points at a next hop it can no longer use, so traffic from {s} to {d} stops there."
        return title, technical, human, "Traffic stops at an unusable next hop"

    if ftype == "FLOW_BLOCKED":
        title = f"{s} to {d} ({sv}) is now dropped at {stop}"
        technical = f"{lead}{dec}Before: {bp}. After: {c['after_detail']}."
        human = f"Traffic from {s} to {d} used to arrive. After this change {stop} blocks it."
        return title, technical, human, "Required traffic is blocked"

    if ftype == "NEW_EXPOSURE":
        srcs = _join(c["sources"])
        title = f"{d} becomes reachable from {srcs}"
        technical = (
            f"{lead}{dec}Probing every endpoint pair on the services in the configuration, {d} was not "
            f"reachable from {srcs} before and is reachable after ({_join(c['services'])}). "
            f"Example path after the change: {ap}."
        )
        human = (
            f"{d} could not be reached from {srcs} before. After this change it can be reached "
            f"on {_join(c['services'])}. No policy covers this, so check that it is intended."
        )
        return title, technical, human, f"{d} gains new reachability"

    if ftype == "PATH_CHANGED":
        title = f"{s} to {d} ({sv}) takes a different path"
        technical = f"{lead}{dec}Path changes from {bp} to {ap}."
        human = f"Traffic from {s} to {d} still arrives, but by a different route. No policy is broken."
        return title, technical, human, "Path changes, still delivered"

    if ftype == "FLOW_RESTORED":
        title = f"{s} to {d} ({sv}) is delivered again"
        technical = f"{lead}{dec}Before: {c['before_detail']}. After: delivered along {ap}."
        human = f"Traffic from {s} to {d} did not arrive before. After this change it does."
        return title, technical, human, "Traffic is delivered"

    if ftype == "NEW_REACHABILITY":
        title = f"{s} to {d} ({sv}) is now reachable"
        technical = f"{lead}{dec}Before: {c['before_detail']}. After: delivered along {ap}."
        human = f"Traffic from {s} to {d} did not arrive before. After this change it does."
        return title, technical, human, "Traffic is delivered"

    return ftype, "", "", ftype
